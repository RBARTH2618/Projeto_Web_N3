-- =============================================================================
-- SISTEMA WEB DE TABELA DE VIDA ECOLÓGICA E ANÁLISE DE FATOR-CHAVE (UniRV)
-- Esquema Relacional PostgreSQL: 9 Tabelas Normalizadas + 2 Views Analíticas
-- Carga Inicial: 4 Usuários, 4 Áreas Experimentais UniRV, 8 Culturas, 30 Pragas e 3 Cenários
-- =============================================================================

DROP VIEW IF EXISTS vw_soma_fases_por_talhao;
DROP VIEW IF EXISTS vw_resumo_cenarios;
DROP TABLE IF EXISTS contagens_fase CASCADE;
DROP TABLE IF EXISTS amostras_coleta CASCADE;
DROP TABLE IF EXISTS talhoes CASCADE;
DROP TABLE IF EXISTS cenario_fases CASCADE;
DROP TABLE IF EXISTS cenarios_analiticos CASCADE;
DROP TABLE IF EXISTS pragas CASCADE;
DROP TABLE IF EXISTS culturas CASCADE;
DROP TABLE IF EXISTS areas_experimentais CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

-- 1. TABELA DE USUÁRIOS / AGRÔNOMOS
CREATE TABLE usuarios (
  id VARCHAR(64) PRIMARY KEY,
  nome VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL,
  cargo VARCHAR(100) NOT NULL,
  instituicao VARCHAR(150) NOT NULL DEFAULT 'Universidade de Rio Verde (UniRV)'
);

-- 2. TABELA DE ÁREAS EXPERIMENTAIS DA UniRV
CREATE TABLE areas_experimentais (
  id VARCHAR(64) PRIMARY KEY,
  nome VARCHAR(160) NOT NULL,
  subtitulo VARCHAR(200) NOT NULL,
  hectares NUMERIC(10, 2) NOT NULL DEFAULT 145.0,
  lat_centro NUMERIC(10, 6) NOT NULL,
  lng_centro NUMERIC(10, 6) NOT NULL,
  dms_label VARCHAR(120) NOT NULL,
  poligono_coords JSONB NOT NULL
);

-- 3. TABELA DE CULTURAS AGRÍCOLAS
CREATE TABLE culturas (
  id VARCHAR(64) PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  nome_cientifico VARCHAR(150) NOT NULL,
  familia VARCHAR(100) NOT NULL,
  descricao TEXT NOT NULL,
  icone VARCHAR(200) NOT NULL,
  cor_tema VARCHAR(32) NOT NULL DEFAULT '#166534'
);

-- 4. TABELA DE PRAGAS AGRÍCOLAS
CREATE TABLE pragas (
  id VARCHAR(64) PRIMARY KEY,
  cultura_id VARCHAR(64) NOT NULL REFERENCES culturas(id) ON DELETE CASCADE,
  nome VARCHAR(140) NOT NULL,
  nome_cientifico VARCHAR(160) NOT NULL,
  ordem_familia VARCHAR(140) NOT NULL,
  importancia VARCHAR(60) NOT NULL DEFAULT 'Praga Principal / Chave',
  descricao_dano TEXT NOT NULL,
  icone VARCHAR(200) NOT NULL,
  fases_sugeridas JSONB NOT NULL
);

-- 5. TABELA DE CENÁRIOS ANALÍTICOS
CREATE TABLE cenarios_analiticos (
  id VARCHAR(64) PRIMARY KEY,
  nome VARCHAR(200) NOT NULL,
  criado_por VARCHAR(150) NOT NULL,
  usuario_id VARCHAR(64) REFERENCES usuarios(id) ON DELETE SET NULL,
  cultura_id VARCHAR(64) NOT NULL REFERENCES culturas(id) ON DELETE RESTRICT,
  praga_id VARCHAR(64) NOT NULL REFERENCES pragas(id) ON DELETE RESTRICT,
  usar_100rx_planilha BOOLEAN NOT NULL DEFAULT FALSE,
  observacoes TEXT DEFAULT '',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. TABELA DE FASES FENOLÓGICAS DO CENÁRIO
CREATE TABLE cenario_fases (
  id SERIAL PRIMARY KEY,
  cenario_id VARCHAR(64) NOT NULL REFERENCES cenarios_analiticos(id) ON DELETE CASCADE,
  ordem_fase INTEGER NOT NULL,
  codigo_fase VARCHAR(32) NOT NULL,
  nome_fase VARCHAR(120) NOT NULL,
  UNIQUE(cenario_id, ordem_fase)
);

-- 7. TABELA DE TALHÕES EXPERIMENTAIS
CREATE TABLE talhoes (
  id SERIAL PRIMARY KEY,
  cenario_id VARCHAR(64) NOT NULL REFERENCES cenarios_analiticos(id) ON DELETE CASCADE,
  area_experimental_id VARCHAR(64) REFERENCES areas_experimentais(id) ON DELETE SET NULL,
  numero_talhao INTEGER NOT NULL,
  nome_talhao VARCHAR(100) NOT NULL,
  lat_centro NUMERIC(10, 6) NOT NULL,
  lng_centro NUMERIC(10, 6) NOT NULL,
  UNIQUE(cenario_id, numero_talhao)
);

-- 8. TABELA DE AMOSTRAS GEORREFERENCIADAS DE COLETA
CREATE TABLE amostras_coleta (
  id SERIAL PRIMARY KEY,
  talhao_id INTEGER NOT NULL REFERENCES talhoes(id) ON DELETE CASCADE,
  indice_amostra INTEGER NOT NULL,
  codigo_amostra VARCHAR(32) NOT NULL,
  latitude NUMERIC(10, 6) NOT NULL,
  longitude NUMERIC(10, 6) NOT NULL,
  UNIQUE(talhao_id, indice_amostra)
);

-- 9. TABELA DE CONTAGENS POR FASE E AMOSTRA
CREATE TABLE contagens_fase (
  id SERIAL PRIMARY KEY,
  talhao_id INTEGER NOT NULL REFERENCES talhoes(id) ON DELETE CASCADE,
  ordem_fase INTEGER NOT NULL,
  indice_amostra INTEGER NOT NULL,
  quantidade_individuos INTEGER NOT NULL DEFAULT 0 CHECK (quantidade_individuos >= 0),
  UNIQUE(talhao_id, ordem_fase, indice_amostra)
);

CREATE INDEX idx_pragas_cultura ON pragas(cultura_id);
CREATE INDEX idx_cenario_fases_cenario ON cenario_fases(cenario_id);
CREATE INDEX idx_talhoes_cenario ON talhoes(cenario_id);
CREATE INDEX idx_amostras_talhao ON amostras_coleta(talhao_id);
CREATE INDEX idx_contagens_talhao ON contagens_fase(talhao_id);

-- VIEW 1: RESUMO DOS CENÁRIOS ANALÍTICOS
CREATE VIEW vw_resumo_cenarios AS
SELECT
  c.id,
  c.nome,
  c.criado_por,
  c.cultura_id,
  cu.nome AS cultura_nome,
  cu.nome_cientifico AS cultura_cientifico,
  c.praga_id,
  pr.nome AS praga_nome,
  pr.nome_cientifico AS praga_cientifico,
  c.usar_100rx_planilha,
  c.observacoes,
  c.criado_em,
  COUNT(DISTINCT t.id) AS total_talhoes,
  COUNT(DISTINCT cf.id) AS total_fases
FROM cenarios_analiticos c
JOIN culturas cu ON cu.id = c.cultura_id
JOIN pragas pr ON pr.id = c.praga_id
LEFT JOIN talhoes t ON t.cenario_id = c.id
LEFT JOIN cenario_fases cf ON cf.cenario_id = c.id
GROUP BY c.id, cu.nome, cu.nome_cientifico, pr.nome, pr.nome_cientifico;

-- VIEW 2: SOMA DE INDIVÍDUOS POR FASE E TALHÃO
CREATE VIEW vw_soma_fases_por_talhao AS
SELECT
  t.cenario_id,
  t.id AS talhao_id,
  t.numero_talhao,
  t.nome_talhao,
  cf.ordem_fase,
  cf.codigo_fase,
  cf.nome_fase,
  COALESCE(SUM(cnt.quantidade_individuos), 0) AS soma_individuos
FROM talhoes t
JOIN cenario_fases cf ON cf.cenario_id = t.cenario_id
LEFT JOIN contagens_fase cnt ON cnt.talhao_id = t.id AND cnt.ordem_fase = cf.ordem_fase
GROUP BY t.cenario_id, t.id, t.numero_talhao, t.nome_talhao, cf.ordem_fase, cf.codigo_fase, cf.nome_fase;

